function shareGlobalLink() {
    const currentUrl = window.location.href;
    const lang = getLang();
    const t = translations[lang];
    const shareTitle = document.title;
    const shareData = {
        title: shareTitle,
        url: currentUrl
    };

    if (navigator.share) {
        navigator.share(shareData)
            .catch((err) => {
                console.log('Share API error or cancelled:', err);
                // Fallback to clipboard on error
                copyToClipboard(currentUrl, t);
            });
    } else {
        // Fallback for browsers that don't support Web Share API
        copyToClipboard(currentUrl, t);
    }
}

function copyToClipboard(text, t) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(text).then(() => {
            showGlobalToast(t.toast_link_copied || '링크가 클립보드에 복사되었습니다!');
        }).catch(err => {
            console.error('Clipboard copy failed:', err);
            fallbackCopyTextToClipboard(text, t);
        });
    } else {
        fallbackCopyTextToClipboard(text, t);
    }
}

function fallbackCopyTextToClipboard(text, t) {
    var textArea = document.createElement("textarea");
    textArea.value = text;
    textArea.style.top = "0";
    textArea.style.left = "0";
    textArea.style.position = "fixed";
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    try {
        document.execCommand('copy');
        showGlobalToast(t.toast_link_copied || '링크가 클립보드에 복사되었습니다!');
    } catch (err) {
        console.error('Fallback: Oops, unable to copy', err);
        alert('링크 복사에 실패했습니다.');
    }
    document.body.removeChild(textArea);
}

function showGlobalToast(msg) {
    let toast = document.getElementById('global-toast');
    if (!toast) {
        toast = document.createElement('div');
        toast.id = 'global-toast';
        document.body.appendChild(toast);
    }
    toast.textContent = msg;
    toast.className = 'toast show';
    // Remove the class after 3 seconds
    setTimeout(() => { 
        toast.className = toast.className.replace('show', '').trim(); 
    }, 3000);
}

// ===== Mobile Menu & Dropdown Toggle =====
document.addEventListener('DOMContentLoaded', () => {
    const menuToggle = document.querySelector('.menu-toggle');
    const navMenu = document.querySelector('nav');
    if (menuToggle && navMenu) {
        menuToggle.addEventListener('click', (e) => {
            e.stopPropagation();
            navMenu.classList.toggle('active');
        });
    }

    const dropdownToggle = document.querySelector('.dropdown-toggle');
    if (dropdownToggle) {
        dropdownToggle.addEventListener('click', (e) => {
            if (window.innerWidth <= 992) {
                e.preventDefault();
                e.stopPropagation();
                const parent = dropdownToggle.closest('.nav-dropdown');
                if (parent) {
                    parent.classList.toggle('open');
                }
            }
        });
    }

    document.addEventListener('click', (e) => {
        if (navMenu && navMenu.classList.contains('active')) {
            if (!navMenu.contains(e.target) && !menuToggle.contains(e.target)) {
                navMenu.classList.remove('active');
            }
        }
    });

    // ===== Dynamic Noindex Handler for Parameterized URLs =====
    if (window.location.search && window.location.search.length > 1) {
        let robotsMeta = document.querySelector('meta[name="robots"]');
        if (!robotsMeta) {
            robotsMeta = document.createElement('meta');
            robotsMeta.name = 'robots';
            document.head.appendChild(robotsMeta);
        }
        robotsMeta.content = 'noindex, follow';
    }
});


